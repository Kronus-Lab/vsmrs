    async fn send(router: Router, method: Method, uri: &str) -> Response {
        let request = Request::builder()
            .method(method)
            .uri(uri)
            .body(Body::empty())
            .expect("valid request");
        router.oneshot(request).await.expect("handler responds")
    }

    /// Signs a cookie value with the key the router derives from SESSION_SECRET.
    fn signed_cookie_value(name: &str, value: &str) -> String {
        let mut jar = cookie::CookieJar::new();
        jar.signed_mut(&crate::session::signing_key("itsasecret"))
            .add((name.to_owned(), value.to_owned()));
        jar.get(name)
            .expect("signed cookie is present")
            .value()
            .to_owned()
    }

    async fn send_with_cookie(
        router: Router,
        method: Method,
        uri: &str,
        name: &str,
        value: &str,
    ) -> Response {
        let request = Request::builder()
            .method(method)
            .uri(uri)
            .header(header::COOKIE, format!("{name}={value}"))
            .body(Body::empty())
            .expect("valid request");
        router.oneshot(request).await.expect("handler responds")
    }

