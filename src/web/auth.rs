/// Redis TTL for a token record: the provider's remaining lifetime, in whole
/// seconds rounded up. `expires_at` remains authoritative at read time.
fn token_ttl_secs(expires_at: f64, now: f64) -> u64 {
    let remaining = expires_at - now;
    if remaining.is_nan() || remaining <= 0.0 {
        return 1;
    }
    remaining.ceil() as u64
}

/// Fractional Unix seconds, so the TTL uses the same clock as `expires_at`.
fn unix_now() -> f64 {
    time::OffsetDateTime::now_utc().unix_timestamp_nanos() as f64 / 1_000_000_000.0
}

/// A 302 response. Axum 0.8 only exposes 303/307/308 `Redirect` constructors,
/// so the status is overridden on a redirect carrying the `Location` header.
fn found(uri: &str) -> Response {
    let mut response = Redirect::temporary(uri).into_response();
    *response.status_mut() = StatusCode::FOUND;
    response
}

/// `GET /auth/login`: build the authorization request, remember its one-time
/// state, and redirect the browser to the identity provider.
pub async fn login(State(state): State<AppState>, jar: SignedCookieJar) -> Response {
    // Building the authorization request retries discovery when startup's
    // attempt failed, so a provider that comes back online needs no restart.
    let Ok((url, pending)) = state.oidc.authorization_request().await else {
        // No provider error detail is logged: upstream responses may carry
        // token material that must not reach the logs.
        debug!("OIDC discovery is unavailable");
        return PageError(AppError::Upstream).into_response();
    };
    // The state is the random id generated by `new_uuid`; the callback looks
    // up exactly this key, so a mismatched state cannot resume the flow.
    state
        .store
        .put_pending(
            &format!("oidc:{}", pending.state),
            &pending,
            PENDING_LOGIN_TTL_SECS,
        )
        .await;
    // The same random id is signed into a short-lived cookie, so a callback
    // from a browser that never started this login cannot consume the record.
    let cookie = build_pending_cookie(
        state.config.is_development(),
        &state.config.hostname,
        &pending.state,
    );
    (jar.add(cookie), found(url.as_str())).into_response()
}

/// Callback query: only `state` and `code` are used; `error`/`session_state`
/// from the identity provider are ignored.
#[derive(Debug, Deserialize)]
pub struct CallbackQuery {
    pub state: Option<String>,
    pub code: Option<String>,
}

/// `GET /auth/callback`: consume the pending login first, then exchange the
/// code and start a session. Every failure short-circuits without issuing a
/// cookie or token record.
pub async fn callback(
    Query(query): Query<CallbackQuery>,
    State(state): State<AppState>,
    jar: SignedCookieJar,
) -> Response {
    let Some(query_state) = query.state else {
        return PageError(AppError::BadState).into_response();
    };
    // The signed cookie is the browser-held proof for this login. Verify it
    // before touching Redis so a stolen state alone cannot start a session.
    let Some(pending_cookie) = jar
        .get(PENDING_COOKIE_NAME)
        .map(|cookie| cookie.value().to_owned())
    else {
        debug!("OIDC callback has no pending-login cookie");
        return PageError(AppError::BadState).into_response();
    };
    if !bool::from(pending_cookie.as_bytes().ct_eq(query_state.as_bytes())) {
        debug!("OIDC callback pending-login cookie does not match state");
        return PageError(AppError::BadState).into_response();
    }

    let Some(pending) = state
        .store
        .take_pending(&format!("oidc:{query_state}"))
        .await
    else {
        return PageError(AppError::BadState).into_response();
    };

    let Some(code) = query.code else {
        // No authorization code: the provider did not issue a token.
        return found("/").into_response();
    };
    let user_info = match state
        .oidc
        .complete(&code, &pending.nonce, &pending.pkce_verifier)
        .await
    {
        Ok(user_info) => user_info,
        Err(_) => {
            // Deliberately log no error detail: upstream responses may carry
            // token material and must never reach the logs.
            debug!("OIDC callback failed");
            return PageError(AppError::Unauthenticated).into_response();
        }
    };

    let uuid = new_uuid();
    let record: TokenRecord = user_info.into_token_record(new_uuid());
    let ttl_secs = token_ttl_secs(record.expires_at, unix_now());
    if state.store.put(&uuid, &record, ttl_secs).await.is_err() {
        return PageError(AppError::Internal).into_response();
    }

    let cookie = build_session_cookie(state.config.is_development(), &state.config.hostname, &uuid);
    // Clear the pending proof only once a session has been issued, so the
    // cookie and the one-shot Redis record cannot be replayed.
    let mut removal =
        build_pending_cookie(state.config.is_development(), &state.config.hostname, "");
    removal.set_max_age(Duration::ZERO);
    (jar.add(cookie).remove(removal), found("/")).into_response()
}

/// `POST /auth/logout`: an anonymous logout is a no-op; an authenticated one
/// validates CSRF, deletes the token and clears the cookie. The body is read
/// as raw bytes so an anonymous POST with no form content-type still succeeds.
pub async fn logout(State(state): State<AppState>, jar: SignedCookieJar, body: Bytes) -> Response {
    let Some(cookie) = jar.get("session") else {
        return found("/").into_response();
    };
    let uuid = cookie.value().to_owned();
    let Some(record) = state.store.get(&uuid).await else {
        return found("/").into_response();
    };

    let supplied = url::form_urlencoded::parse(&body)
        .find(|(key, _)| key == "csrf_token")
        .map(|(_, value)| value.into_owned())
        .unwrap_or_default();
    if !bool::from(supplied.as_bytes().ct_eq(record.csrf_token.as_bytes())) {
        return PageError(AppError::BadCsrf).into_response();
    }

    state.store.delete(&uuid).await;
    let mut removal =
        build_session_cookie(state.config.is_development(), &state.config.hostname, "");
    removal.set_max_age(Duration::ZERO);
    (jar.remove(removal), found("/")).into_response()
}

/// `GET /auth/logout` is not supported; the browser must POST with CSRF.
pub async fn logout_get() -> Response {
    (StatusCode::METHOD_NOT_ALLOWED, [(header::ALLOW, "POST")]).into_response()
}

