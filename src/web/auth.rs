    #[tokio::test]
    async fn login_sets_signed_pending_cookie() {
        let store = Arc::new(CountingStore::new());

        let response = send(app(store.clone()), Method::GET, "/auth/login").await;

        assert_eq!(response.status(), StatusCode::FOUND);
        let set_cookie = response
            .headers()
            .get(header::SET_COOKIE)
            .and_then(|value| value.to_str().ok())
            .expect("login sets a pending cookie")
            .to_owned();
        assert!(set_cookie.starts_with("oidc_pending="), "{set_cookie}");
        assert!(set_cookie.contains("HttpOnly"), "{set_cookie}");
        assert!(set_cookie.contains("SameSite=Strict"), "{set_cookie}");
        assert!(set_cookie.contains("Path=/"), "{set_cookie}");
        assert!(set_cookie.contains("Max-Age=600"), "{set_cookie}");
        assert_eq!(store.pending_puts.load(Ordering::SeqCst), 1);

        let location = response
            .headers()
            .get(header::LOCATION)
            .and_then(|value| value.to_str().ok())
            .expect("login redirects to the provider");
        let query = Url::parse(location).expect("valid authorization URL");
        let state = query
            .query_pairs()
            .find(|(key, _)| key == "state")
            .map(|(_, value)| value.into_owned())
            .expect("authorization request carries state");
        let cookie_value = set_cookie
            .split(';')
            .next()
            .expect("cookie pair")
            .strip_prefix("oidc_pending=")
            .expect("cookie name");
        // Signed cookie values are emitted as `signature=payload=<state>`;
        // the plaintext state is the final segment of the signed value.
        assert!(
            cookie_value.ends_with(&state),
            "the signed cookie must carry the Redis pending id: {cookie_value}"
        );
        assert!(
            store
                .inner
                .take_pending(&format!("oidc:{state}"))
                .await
                .is_some(),
            "the pending record must be stored under the signed state"
        );
    }

