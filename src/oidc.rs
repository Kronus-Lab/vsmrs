    #[tokio::test]
    async fn complete_exchanges_code_and_reads_configured_fields() {
        let server = MockServer::start().await;
        let base = server.uri();
        test_support::mount_provider(
            &server,
            json!({
                "access_token": "access-token-value",
                "token_type": "Bearer",
                "expires_in": 3600,
                "id_token": test_support::signed_id_token(&base, "some-nonce"),
            }),
            1,
        )
        .await;

        let config = test_support::config(&base);
        let client = OidcClient::new(&config).await.expect("discovery succeeds");

        let info = client
            .complete("some-code", "some-nonce", "some-verifier")
            .await
            .expect("code exchange and userinfo succeed");
        assert_eq!(info.username, "testuser");
        assert_eq!(info.groups, vec!["/example".to_owned()]);

        let record = info.into_token_record("csrf-value".to_owned());
        assert_eq!(record.access_token, "access-token-value");
        assert_eq!(record.csrf_token, "csrf-value");
        assert!(record.expires_at > super::now_secs());
        assert_eq!(record.userinfo["preferred_username"], json!("testuser"));
        server.verify().await;
    }

    #[tokio::test]
    async fn complete_rejects_token_response_without_id_token() {
        let server = MockServer::start().await;
        test_support::mount_provider(
            &server,
            json!({
                "access_token": "access-token-value",
                "token_type": "Bearer",
                "expires_in": 3600,
            }),
            0,
        )
        .await;

        let config = test_support::config(&server.uri());
        let client = OidcClient::new(&config).await.expect("discovery succeeds");

        let error = client
            .complete("some-code", "some-nonce", "some-verifier")
            .await
            .err()
            .expect("a token response without an ID token is rejected");
        assert!(
            error.to_string().contains("ID token"),
            "unexpected error: {error:#}"
        );
        server.verify().await;
    }

    #[tokio::test]
    async fn new_retains_discovery_failure_without_aborting() {
        let server = MockServer::start().await;
        test_support::mount_failing_discovery(&server).await;
        let config = test_support::config(&server.uri());

        assert!(
            OidcClient::new(&config).await.is_ok(),
            "discovery failure must not abort startup"
        );
        server.verify().await;
    }
