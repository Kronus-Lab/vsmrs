    #[tokio::test]
    async fn authorize_url_uses_contract_parameters() {
        let client = OidcClient::from_parts(
            Url::parse("http://kc.local.kronus.network/realms/devel/protocol/openid-connect/auth")
                .expect("valid authorize URL"),
            "vsm".to_owned(),
            Url::parse("http://localhost/auth/callback").expect("valid callback URL"),
        );

        let (url, pending) = client
            .authorization_request()
            .await
            .expect("authorization request builds");

        let params: HashMap<String, String> = url
            .query_pairs()
            .map(|(key, value)| (key.into_owned(), value.into_owned()))
            .collect();
        assert_eq!(params.get("client_id").map(String::as_str), Some("vsm"));
        assert_eq!(
            params.get("redirect_uri").map(String::as_str),
            Some("http://localhost/auth/callback")
        );
        assert_eq!(
            params.get("scope").map(String::as_str),
            Some("openid email profile")
        );
        assert_eq!(
            params.get("code_challenge_method").map(String::as_str),
            Some("S256")
        );
        assert!(!params["state"].is_empty());
        assert_eq!(params["state"], pending.state);
        assert!(!params["nonce"].is_empty());
        assert_eq!(params["nonce"], pending.nonce);
        assert_ne!(params["code_challenge"], pending.pkce_verifier);
    }

    #[tokio::test]
    async fn pending_login_is_single_use() {
        let store = MemoryStore::new();
        let pending = PendingLogin {
            state: "state-value".to_owned(),
            nonce: "nonce-value".to_owned(),
            pkce_verifier: "verifier-value".to_owned(),
        };

        store.put_pending("oidc:login", &pending, 600).await;

        let taken = store
            .take_pending("oidc:login")
            .await
            .expect("pending login is stored once");
        assert_eq!(taken.state, pending.state);
        assert_eq!(taken.nonce, pending.nonce);
        assert_eq!(taken.pkce_verifier, pending.pkce_verifier);
        assert!(store.take_pending("oidc:login").await.is_none());
    }

